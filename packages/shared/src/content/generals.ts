// stat, skill, and effect value here is our own independent design: we
// deliberately did NOT use any commercial game's specific numeric stat
// database, its "개성"/전법 taxonomy, or its character-to-ability mappings,
// since that specific compilation is that game's proprietary creative
// content rather than public-domain history. The ~70 most iconic figures
